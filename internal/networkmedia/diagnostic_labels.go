func playbackDiagnostic(kind, stage, code string) string {
	messages := errorMessages[say.Chosen()]
	if messages == nil {
		messages = errorMessages["en"]
	}
	summary := messages[kind]
	if summary == "" {
		summary = messages["unknown"]
	}
	step := messages["stage_"+stage]
	if step == "" {
		step = messages["stage_operation"]
	}
	return fmt.Sprintf(messages["format"], summary, step, code)
}
